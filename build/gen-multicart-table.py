#!/usr/bin/env python3
"""Generates app/ui/multicart_table.h: the DS games that play with one card per console, from GameTDB's DS database.

    build/gen-multicart-table.py [dstdb.xml or dstdb.zip]     (none: downloads https://www.gametdb.com/dstdb.zip)

The table keeps, for each game code's first three letters (the fourth is the region), the most players with one
card each (<input players-multi-cart="N">) that GameTDB gives its releases in America, Europe and Australia, when
that is 2 or more; a game with no such release takes the others'. Their Japanese and Korean entries often give the
game's players as multi-card ones (Mario Party DS: 4 there, 1 in the others, a DS Download Play game), so they only
count when there's nothing else.
DS Download Play isn't in it: the app reads that from the ROM itself (rominfo.c).
GameTDB (https://www.gametdb.com) is a community database; its FAQ allows its use in software with a link to it.
"""
import io, re, sys, urllib.request, zipfile, os

# the region letters of America, Europe and Australia (E USA, P Europe, D F I S H the European languages, U Australia,
# L N V W X Y Z other western releases)
WEST = set("EPDFISHULNVWXYZ")
URL = "https://www.gametdb.com/dstdb.zip?LANG=EN"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "ui", "multicart_table.h")


def load(arg):
    if arg and arg.endswith(".xml"):
        return open(arg, encoding="utf-8").read()
    data = open(arg, "rb").read() if arg else urllib.request.urlopen(
        urllib.request.Request(URL, headers={"User-Agent": "banana-party table generator"}), timeout=60).read()
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return z.read("dstdb.xml").decode("utf-8")


def main():
    xml = load(sys.argv[1] if len(sys.argv) > 1 else None)
    ver = re.search(r'<DSTDB version="(\d+)"', xml)
    west, other = {}, {}
    for body in re.findall(r"<game [^>]*>(.*?)</game>", xml, re.S):
        gid = re.search(r"<id>([0-9A-Z]{4})</id>", body)
        inp = re.search(r'<input[^>]*players-multi-cart="(\d+)"', body)
        if not gid or not inp:
            continue
        n = int(inp.group(1) or 0)
        base, region = gid.group(1)[:3], gid.group(1)[3]
        d = west if region in WEST else other
        d[base] = max(d.get(base, 0), n)
    best = {}
    for base in set(west) | set(other):
        n = west[base] if base in west else other[base]
        if n >= 2:
            best[base] = min(n, 255)
    rows = sorted(best.items())
    with open(OUT, "w") as f:
        f.write("/* Generated by build/gen-multicart-table.py from GameTDB's DS database (https://www.gametdb.com),\n")
        f.write(" * version %s. Do not edit: run the script again.\n" % (ver.group(1) if ver else "?"))
        f.write(" * A game code's first three letters, and the most players with one card each (2 or more). */\n")
        f.write("#define MULTICART_N %d\n" % len(rows))
        f.write("static const char multicart_ids[MULTICART_N][3] = {\n")
        for i in range(0, len(rows), 12):
            f.write("    " + " ".join("{'%s','%s','%s'}," % tuple(k) for k, _ in rows[i:i + 12]) + "\n")
        f.write("};\nstatic const unsigned char multicart_players[MULTICART_N] = {\n")
        for i in range(0, len(rows), 24):
            f.write("    " + " ".join("%d," % v for _, v in rows[i:i + 24]) + "\n")
        f.write("};\n")
    print("%s: %d games (GameTDB DS %s)" % (os.path.relpath(OUT, ROOT), len(rows), ver.group(1) if ver else "?"))


if __name__ == "__main__":
    main()
